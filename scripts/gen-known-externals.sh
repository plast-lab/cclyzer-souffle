#!/usr/bin/env bash
#
# Regenerate scripts/known-externals.txt: the functions exported by the C,
# math, POSIX, C++ and compiler runtime libraries of this system. The
# whole-program check treats calls to these as legitimately external.

set -euo pipefail
OUT=$(dirname "$0")/known-externals.txt
libs=(libc.so.6 libm.so.6 libresolv.so.2 libcrypt.so.1 libstdc++.so.6 libgcc_s.so.1)

{
    echo "# Functions exported by: ${libs[*]}"
    echo "# Generated by scripts/gen-known-externals.sh on $(ldd --version | head -n 1)"
    {
    for l in "${libs[@]}"; do
        p=$(ldconfig -p | awk -v l="$l" '$1 == l && /x86-64/ && !found { print $NF; found = 1 }')
        [ -n "$p" ] || { echo "warning: $l not found" >&2; continue; }
        nm -D --defined-only "$p" | awk '$2 ~ /^[TWiV]$/ { print $3 }' | sed 's/@.*//'
    done
    # glibc puts a few functions (atexit, at_quick_exit, ...) in a static archive
    nonshared=$(gcc -print-file-name=libc_nonshared.a)
    [ -f "$nonshared" ] && nm --defined-only "$nonshared" 2>/dev/null | awk '$2 ~ /^[TW]$/ { print $3 }'
    } | sort -u
} > "$OUT"
echo "$(grep -vc '^#' "$OUT") names -> $OUT"
